-- Synchronize a legacy member reference to its Phase 2 identity. New athletes
-- without a legacy row keep member_id NULL; callers must use the new columns.
CREATE OR REPLACE FUNCTION public.sync_phase2_identity_compatibility()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
DECLARE
  mapped record;
  membership record;
BEGIN
  IF NEW.member_id IS NOT NULL THEN
    SELECT identity_map.athlete_id,
           identity_map.club_membership_id,
           club_membership.club_id
      INTO mapped
    FROM public.club_member_athlete_map AS identity_map
    JOIN public.club_memberships AS club_membership
      ON club_membership.id = identity_map.club_membership_id
    WHERE identity_map.legacy_club_member_id = NEW.member_id;

    IF mapped.club_membership_id IS NULL THEN
      RAISE EXCEPTION 'No Phase 2 identity mapping for legacy member %', NEW.member_id;
    END IF;
    IF NEW.athlete_id IS NOT NULL AND NEW.athlete_id <> mapped.athlete_id THEN
      RAISE EXCEPTION 'athlete_id conflicts with legacy member %', NEW.member_id;
    END IF;
    IF NEW.club_membership_id IS NOT NULL
       AND NEW.club_membership_id <> mapped.club_membership_id THEN
      RAISE EXCEPTION 'club_membership_id conflicts with legacy member %', NEW.member_id;
    END IF;

    NEW.athlete_id := mapped.athlete_id;
    NEW.club_membership_id := mapped.club_membership_id;
    IF TG_TABLE_NAME = 'tournament_entrant_members' THEN
      NEW.membership_club_id := mapped.club_id;
    ELSIF NEW.group_id <> mapped.club_id THEN
      RAISE EXCEPTION 'membership club % conflicts with participant group %', mapped.club_id, NEW.group_id;
    END IF;
  ELSIF NEW.club_membership_id IS NOT NULL THEN
    SELECT id, club_id, athlete_id INTO membership
    FROM public.club_memberships
    WHERE id = NEW.club_membership_id;

    IF membership.id IS NULL THEN
      RAISE EXCEPTION 'Unknown club membership %', NEW.club_membership_id;
    END IF;
    IF NEW.athlete_id IS NOT NULL AND NEW.athlete_id <> membership.athlete_id THEN
      RAISE EXCEPTION 'athlete_id conflicts with club membership %', NEW.club_membership_id;
    END IF;
    NEW.athlete_id := membership.athlete_id;

    IF TG_TABLE_NAME = 'tournament_entrant_members' THEN
      NEW.membership_club_id := membership.club_id;
    ELSIF NEW.group_id <> membership.club_id THEN
      RAISE EXCEPTION 'membership club % conflicts with participant group %', membership.club_id, NEW.group_id;
    END IF;
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS fund_event_participants_sync_phase2_identity
  ON public.fund_event_participants;
CREATE TRIGGER fund_event_participants_sync_phase2_identity
BEFORE INSERT OR UPDATE OF member_id, athlete_id, club_membership_id, group_id
ON public.fund_event_participants
FOR EACH ROW EXECUTE FUNCTION public.sync_phase2_identity_compatibility();

DROP TRIGGER IF EXISTS tournament_entrant_members_sync_phase2_identity
  ON public.tournament_entrant_members;
CREATE TRIGGER tournament_entrant_members_sync_phase2_identity
BEFORE INSERT OR UPDATE OF member_id, athlete_id, club_membership_id, membership_club_id
ON public.tournament_entrant_members
FOR EACH ROW EXECUTE FUNCTION public.sync_phase2_identity_compatibility();

