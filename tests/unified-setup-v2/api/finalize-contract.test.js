const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '../../..');
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8');
const assert = (value, message) => { if (!value) throw new Error(message); };
const route = read('app/api/tournament-v2/setup/finalize/route.js');
const setupRoute = read('app/api/tournament-v2/setup/route.js');
const useCase = read('lib/tournament/setupFinalize.js');
const migration = read('database/migrations/090_unified_setup_friendly_invites.sql');
assert(route.includes('requireValidatedGroupAdmin'), 'finalize must require admin');
assert(route.includes("'finalize_unified_setup_v2'"), 'finalize must use atomic wrapper RPC');
assert(useCase.includes('FINALIZE_NOT_ATOMIC'), 'finalize must expose atomic failure code');
assert(route.includes('p_group_id'), 'finalize must scope group');
assert(!route.includes('tournament_draw_slots'), 'finalize must not use draw slots');
assert(useCase.includes('IDEMPOTENCY_KEY_REUSED'), 'idempotency error must be stable');
assert(useCase.includes('REVISION_CONFLICT'), 'revision error must be stable');
assert(route.includes("organizerMode === 'friendly'") && route.includes('NO_CLUB_INVITED'), 'friendly finalize must block when no club is invited');
assert(route.includes('p_invited_clubs: invitedClubs'), 'finalize must send invited clubs to the atomic RPC');
assert(setupRoute.includes("action === 'replace_invited_clubs'"), 'setup save must support replace_invited_clubs');
assert(setupRoute.includes('invitedClubs:'), 'setup GET must return invitedClubs for resume');
assert(migration.includes('replace_tournament_invited_clubs_revisioned'), 'migration must add revisioned friendly invite save RPC');
assert(migration.includes("operation = 'replace_tournament_invited_clubs_revisioned'"), 'friendly save RPC must use idempotency ledger');
assert(migration.includes('ON CONFLICT (tournament_id, club_id)') && migration.includes("invitation_status = 'invited'"), 'duplicate system clubs must resolve as invited');
assert(migration.includes('p_invited_clubs jsonb') && migration.includes('CREATE OR REPLACE FUNCTION public.finalize_unified_setup_v2'), 'finalize RPC must accept invited clubs in the same transaction');
console.log('unified setup finalize API contract ok');
