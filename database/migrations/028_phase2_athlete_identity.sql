-- PickHub Phase 2: athlete identity, club memberships and revocable club sessions.
-- Apply after 027_index_member_origin_fk.sql. The legacy club_members model stays
-- writable during this compatibility window; no account/profile row is required.

BEGIN;

ALTER TABLE public.groups
  ADD COLUMN IF NOT EXISTS access_version bigint NOT NULL DEFAULT 1;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conrelid = 'public.groups'::regclass
      AND conname = 'groups_access_version_positive'
  ) THEN
    ALTER TABLE public.groups
      ADD CONSTRAINT groups_access_version_positive CHECK (access_version > 0);
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS public.athletes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  display_name text NOT NULL CHECK (btrim(display_name) <> ''),
  normalized_name text NOT NULL CHECK (btrim(normalized_name) <> ''),
  status text NOT NULL DEFAULT 'unclaimed'
    CHECK (status IN ('unclaimed', 'linked', 'merged', 'restricted', 'deleted')),
  merged_into_athlete_id bigint REFERENCES public.athletes(id) ON DELETE RESTRICT,
  legacy_club_member_id bigint UNIQUE REFERENCES public.club_members(id) ON DELETE RESTRICT,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (
    (status = 'merged' AND merged_into_athlete_id IS NOT NULL)
    OR (status <> 'merged' AND merged_into_athlete_id IS NULL)
  ),
  CHECK (merged_into_athlete_id IS NULL OR merged_into_athlete_id <> id)
);

CREATE TABLE IF NOT EXISTS public.club_memberships (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  club_id bigint NOT NULL REFERENCES public.groups(id) ON DELETE RESTRICT,
  athlete_id bigint NOT NULL REFERENCES public.athletes(id) ON DELETE RESTRICT,
  status text NOT NULL DEFAULT 'active'
    CHECK (status IN ('active', 'inactive', 'suspended', 'ended')),
  effective_from date NOT NULL DEFAULT current_date,
  effective_to date,
  joined_on date,
  left_on date,
  club_alias text,
  primary_for_athlete boolean NOT NULL DEFAULT false,
  private_notes text,
  version bigint NOT NULL DEFAULT 1 CHECK (version > 0),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (effective_to IS NULL OR effective_to > effective_from),
  CHECK (left_on IS NULL OR joined_on IS NULL OR left_on >= joined_on),
  UNIQUE NULLS NOT DISTINCT (club_id, athlete_id, effective_to)
);

-- PostgreSQL requires this key to exist before the assessment composite FK is
-- declared. The primary key on id remains the row identity.
CREATE UNIQUE INDEX IF NOT EXISTS club_memberships_id_club_athlete_key
  ON public.club_memberships(id, club_id, athlete_id);

-- A dedicated map keeps every legacy identifier traceable without making the
-- old row the long-term athlete identity.
CREATE TABLE IF NOT EXISTS public.club_member_athlete_map (
  legacy_club_member_id bigint NOT NULL UNIQUE,
  club_id bigint NOT NULL REFERENCES public.groups(id) ON DELETE RESTRICT,
  athlete_id bigint NOT NULL REFERENCES public.athletes(id) ON DELETE RESTRICT,
  club_membership_id bigint NOT NULL UNIQUE
    REFERENCES public.club_memberships(id) ON DELETE RESTRICT,
  migrated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (legacy_club_member_id),
  CONSTRAINT club_member_athlete_map_legacy_fk
    FOREIGN KEY (legacy_club_member_id, club_id)
    REFERENCES public.club_members(id, group_id)
    ON DELETE RESTRICT,
  CONSTRAINT club_member_athlete_map_membership_fk
    FOREIGN KEY (club_membership_id, club_id, athlete_id)
    REFERENCES public.club_memberships(id, club_id, athlete_id)
    ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS public.membership_assessments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  club_id bigint NOT NULL REFERENCES public.groups(id) ON DELETE RESTRICT,
  club_membership_id bigint NOT NULL,
  athlete_id bigint NOT NULL REFERENCES public.athletes(id) ON DELETE RESTRICT,
  assessed_at timestamptz NOT NULL DEFAULT now(),
  effective_from date NOT NULL DEFAULT current_date,
  skill_level numeric(4, 2) CHECK (skill_level >= 0 AND skill_level <= 10),
  source text NOT NULL DEFAULT 'club_admin'
    CHECK (source IN ('club_admin', 'verified_match', 'import', 'correction')),
  notes text,
  actor_type text NOT NULL DEFAULT 'club_admin_session'
    CHECK (actor_type IN ('club_admin_session', 'platform_admin', 'system')),
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT membership_assessments_membership_fk
    FOREIGN KEY (club_membership_id, club_id, athlete_id)
    REFERENCES public.club_memberships(id, club_id, athlete_id)
    ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS public.group_sessions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  group_id bigint NOT NULL REFERENCES public.groups(id) ON DELETE CASCADE,
  group_code text NOT NULL,
  role text NOT NULL CHECK (role IN ('member', 'admin')),
  session_key_hash text NOT NULL UNIQUE CHECK (btrim(session_key_hash) <> ''),
  issued_at timestamptz NOT NULL,
  expires_at timestamptz NOT NULL,
  session_version bigint NOT NULL CHECK (session_version > 0),
  revoked_at timestamptz,
  revoke_reason text,
  last_seen_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK (expires_at > issued_at),
  CHECK (revoked_at IS NULL OR revoked_at >= issued_at)
);

