UPDATE public.fund_event_participants AS participant
SET athlete_id = identity_map.athlete_id,
    club_membership_id = identity_map.club_membership_id
FROM public.club_member_athlete_map AS identity_map
WHERE participant.member_id = identity_map.legacy_club_member_id
  AND (participant.athlete_id IS NULL OR participant.club_membership_id IS NULL);

UPDATE public.tournament_entrant_members AS entrant_member
SET athlete_id = identity_map.athlete_id,
    club_membership_id = identity_map.club_membership_id,
    membership_club_id = membership.club_id
FROM public.club_member_athlete_map AS identity_map
JOIN public.club_memberships AS membership ON membership.id = identity_map.club_membership_id
WHERE entrant_member.member_id = identity_map.legacy_club_member_id
  AND (
    entrant_member.athlete_id IS NULL
    OR entrant_member.club_membership_id IS NULL
    OR entrant_member.membership_club_id IS NULL
  );

