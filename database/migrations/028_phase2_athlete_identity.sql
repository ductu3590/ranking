-- One athlete and one membership per legacy member. IDs are intentionally
-- reused only for the initial backfill, which makes the migration deterministic
-- while the separate mapping remains the compatibility contract.
INSERT INTO public.athletes (
  id,
  display_name,
  normalized_name,
  status,
  legacy_club_member_id,
  created_at,
  updated_at
)
SELECT
  member.id,
  btrim(member.full_name),
  lower(regexp_replace(btrim(member.full_name), '\s+', ' ', 'g')),
  'unclaimed',
  member.id,
  COALESCE(member.created_at, now()),
  COALESCE(member.updated_at, member.created_at, now())
FROM public.club_members AS member
ON CONFLICT (id) DO NOTHING;

INSERT INTO public.club_memberships (
  id,
  club_id,
  athlete_id,
  status,
  effective_from,
  joined_on,
  club_alias,
  primary_for_athlete,
  created_at,
  updated_at
)
SELECT
  member.id,
  member.group_id,
  athlete.id,
  CASE WHEN member.is_active THEN 'active' ELSE 'inactive' END,
  COALESCE(member.created_at::date, current_date),
  member.created_at::date,
  btrim(member.full_name),
  true,
  COALESCE(member.created_at, now()),
  COALESCE(member.updated_at, member.created_at, now())
FROM public.club_members AS member
JOIN public.athletes AS athlete ON athlete.legacy_club_member_id = member.id
ON CONFLICT (id) DO NOTHING;

INSERT INTO public.club_member_athlete_map (
  legacy_club_member_id,
  club_id,
  athlete_id,
  club_membership_id
)
SELECT member.id, member.group_id, athlete.id, membership.id
FROM public.club_members AS member
JOIN public.athletes AS athlete ON athlete.legacy_club_member_id = member.id
JOIN public.club_memberships AS membership
  ON membership.id = member.id
 AND membership.club_id = member.group_id
 AND membership.athlete_id = athlete.id
ON CONFLICT (legacy_club_member_id) DO NOTHING;

DO $$
DECLARE
  legacy_count bigint;
  mapping_count bigint;
  distinct_athlete_count bigint;
  distinct_membership_count bigint;
BEGIN
  SELECT count(*) INTO legacy_count FROM public.club_members;
  SELECT count(*), count(DISTINCT athlete_id), count(DISTINCT club_membership_id)
    INTO mapping_count, distinct_athlete_count, distinct_membership_count
  FROM public.club_member_athlete_map;

  IF mapping_count <> legacy_count
     OR distinct_athlete_count <> legacy_count
     OR distinct_membership_count <> legacy_count THEN
    RAISE EXCEPTION
      'Phase 2 identity backfill mismatch: legacy %, mappings %, athletes %, memberships %',
      legacy_count, mapping_count, distinct_athlete_count, distinct_membership_count;
  END IF;
END $$;

